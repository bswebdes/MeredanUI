-- Macro templates per class for the "Templates" tab of the macro window (Skins/MacroTemplates.lua).
--
-- body tokens (resolved when the macro is built, so the text is in the client's language):
--   {id}        spell name                       {id r}  -> {idr}: name(Rank N) of exactly that rank
--   {a|b|c}     name of the first KNOWN spell (falls back to the first id)
--   <<...>>     optional part: kept only if every spell inside is known (e.g. a Ctrl variant
--               learned later); dropped first when the macro would exceed 255 characters
--   {BEST:spell=item,...}  item:<id> of the last listed spell the player knows (ranked stones)
--   {SHIELDS} / {PET_VOIDWALKER} / {PET_SUCCUBUS} / {PET_FELHUNTER}  localized words
-- Items are referenced as item:<id>, which macros accept in any language.
-- req: spells that must be known (a nested table = any of them). lvl: shown as "from level".
-- Spell ids are Classic/Forever rank-1 ids; new Forever spells use their Forever ids.
local _, ns = ...

local T = {}
ns.MACRO_TEMPLATES = T

local function Add(class, list)
    for _, t in ipairs(list) do
        t.class = class
        T[#T + 1] = t
    end
end

