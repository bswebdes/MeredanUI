#!/usr/bin/env python3
"""Dungeon maps for the dungeon guide (WoW Forever has no dungeon maps of its own).

Forever's client ships Blizzard's drawn dungeon map textures, but no UiMap rows for them. The floor
layout (which uiMap belongs to which instance, floor names, world bounds) comes from wago.tools:
  - uiMaps per instance + world bounds: UiMapAssignment/UiMap of wow_anniversary (vanilla layouts)
  - art tiles: UiMapXMapArt/UiMapArtTile of wow_classic (same uiMap IDs; style 1002x668, 4x3 tiles)
  - floor names enUS/deDE: UiMapGroupMember (wow_classic)
Every tile FileDataID is checked against the Forever build (product wowf) before it is used.

Output: Map/DungeonMapData.lua - ns.DUNGEON_MAPS[instanceMapID] = { floor, ... } with
  floor = { ui, en, de, tiles = { 12 FileDataIDs, row-major }, region = { x1, y1, x2, y2, z1, z2 } }
Usage: python3 -I tools/build_dungeon_maps.py [--refresh]   (CSV cache: tools/mapdata/classic/)
"""
import csv, json, pathlib, sys, urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
CACHE = ROOT / "tools" / "mapdata" / "classic"
WOWF_BUILD = "1.60.1.70862"
REFRESH = "--refresh" in sys.argv

# Instances shown in the guide (classic dungeons and raids that Forever has)
INSTANCES = [33, 34, 36, 43, 47, 48, 70, 90, 109, 129, 189, 209, 229, 230, 249, 289, 309, 329, 349, 389,
             409, 429, 469, 509, 531, 533]

UA = {"User-Agent": "MeredanUI-tools"}  # wago.tools rejects urllib's default agent

def fetch(url):
    return urllib.request.urlopen(urllib.request.Request(url, headers=UA))

def table(name, product, locale=None):
    CACHE.mkdir(parents=True, exist_ok=True)
    path = CACHE / f"{name}_{product}{'_' + locale if locale else ''}.csv"
    if REFRESH or not path.exists():
        url = f"https://wago.tools/db2/{name}/csv?product={product}" + (f"&locale={locale}" if locale else "")
        path.write_bytes(fetch(url).read())
    with open(path, encoding="utf-8") as f:
        return list(csv.DictReader(f))

checked = {}
CHECK_FILE = CACHE / "wowf_files.json"
if CHECK_FILE.exists() and not REFRESH:
    checked = json.loads(CHECK_FILE.read_text())

def in_forever(fdid):
    key = str(fdid)
    if key not in checked:
        head = fetch(f"https://wago.tools/api/casc/{fdid}?version={WOWF_BUILD}").read(4)
        checked[key] = head == b"BLP2"
    return checked[key]

ann_map = {r["ID"]: r for r in table("UiMap", "wow_anniversary")}
ann_assign = table("UiMapAssignment", "wow_anniversary")
mop_map = {r["ID"]: r for r in table("UiMap", "wow_classic")}
mop_map_de = {r["ID"]: r for r in table("UiMap", "wow_classic", "deDE")}
mop_assign = table("UiMapAssignment", "wow_classic")
art_of = {r["UiMapID"]: r["UiMapArtID"] for r in table("UiMapXMapArt", "wow_classic") if r["PhaseID"] == "0"}
tiles_of = {}
for r in table("UiMapArtTile", "wow_classic"):
    if r["LayerIndex"] == "0":
        tiles_of.setdefault(r["UiMapArtID"], []).append((int(r["RowIndex"]), int(r["ColIndex"]), int(r["FileDataID"])))
groups_en = {r["UiMapID"]: r for r in table("UiMapGroupMember", "wow_classic")}
groups_de = {r["ID"]: r for r in table("UiMapGroupMember", "wow_classic", "deDE")}

def ui_maps(instance):
    """uiMaps of an instance: anniversary first (vanilla), else MoP classic. Dungeon (4) or orphan (6) maps."""
    for assign, maps in ((ann_assign, ann_map), (mop_assign, mop_map)):
        found = {}
        for r in assign:
            if r["MapID"] == str(instance) and maps.get(r["UiMapID"], {}).get("Type") in ("4", "6"):
                found.setdefault(r["UiMapID"], []).append(r)
        if found:
            return found
    return {}

def region(rows):
    # the assignment covering the whole map (UiMin 0,0 / UiMax 1,1) gives the world bounds
    for r in rows:
        if float(r["UiMin_0"]) == 0 and float(r["UiMin_1"]) == 0 and float(r["UiMax_0"]) == 1 and float(r["UiMax_1"]) == 1:
            return [round(float(r[f"Region_{i}"]), 2) for i in range(6)]
    r = rows[0]
    return [round(float(r[f"Region_{i}"]), 2) for i in range(6)]

def lua(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'

out = ["-- GENERATED by tools/build_dungeon_maps.py - do not edit by hand.",
       "-- Blizzard's dungeon map textures (shipped with Forever) per instance and floor; layout from wago.tools.",
       "local _, ns = ...", "", "ns.DUNGEON_MAPS = {"]
report = []
for instance in INSTANCES:
    floors = []
    for ui, rows in sorted(ui_maps(instance).items(), key=lambda kv: int(groups_en.get(kv[0], {}).get("FloorIndex", 0) or 0)):
        art = art_of.get(ui)
        tiles = sorted(tiles_of.get(art, [])) if art else []
        if len(tiles) != 12 or not all(in_forever(t[2]) for t in tiles):
            report.append(f"{instance} ui {ui}: no usable art ({len(tiles)} tiles)")
            continue
        group = groups_en.get(ui)
        en = group["Name_lang"] if group and group["Name_lang"] else mop_map.get(ui, ann_map.get(ui, {})).get("Name_lang", "")
        de_group = groups_de.get(group["ID"]) if group else None
        de = de_group["Name_lang"] if de_group and de_group["Name_lang"] else mop_map_de.get(ui, {}).get("Name_lang", en)
        reg = region(rows)
        floors.append("{ ui = %s, en = %s, de = %s, tiles = { %s }, region = { %s } }" % (
            ui, lua(en), lua(de), ", ".join(str(t[2]) for t in tiles), ", ".join(str(v) for v in reg)))
    if floors:
        out.append("    [%d] = {\n        %s,\n    }," % (instance, ",\n        ".join(floors)))
    report.append(f"{instance}: {len(floors)} floor(s)")
out.append("}")
(ROOT / "Map" / "DungeonMapData.lua").write_text("\n".join(out) + "\n", encoding="utf-8")
CHECK_FILE.write_text(json.dumps(checked))
print("\n".join(report))
